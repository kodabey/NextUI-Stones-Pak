#!/usr/bin/env python3
"""Bake font atlases into a C header (8-bit alpha), so the game needs no SDL_ttf."""
import sys
from PIL import Image, ImageDraw, ImageFont

SERIF = "/usr/share/fonts/opentype/noto/NotoSerifCJK-Bold.ttc"
SANS = "/usr/share/fonts/opentype/inter/Inter-SemiBold.otf"
SANS_MED = "/usr/share/fonts/opentype/inter/Inter-Medium.otf"

ASCII = "".join(chr(c) for c in range(32, 127))
SYMS = "×–—…·→←↑↓•©°‹›"
KANJI = "囲碁石川山龍友黒白勝負一局終道"

# (enum name, font file, ttc index, pixel size, charset)
FONTS = [
    ("F_SMALL", SANS_MED, 0, 24, ASCII + SYMS),
    ("F_BODY", SANS, 0, 30, ASCII + SYMS),
    ("F_HEAD", SERIF, 0, 44, ASCII + SYMS + KANJI),
    ("F_BIG", SERIF, 0, 84, ASCII + SYMS + KANJI),
    ("F_HUGE", SERIF, 0, 168, "GO" + KANJI),
]

ATLAS_W = 1024


def bake(path, idx, size, chars):
    font = ImageFont.truetype(path, size, index=idx)
    ascent, descent = font.getmetrics()
    glyphs = []
    for ch in chars:
        bbox = font.getbbox(ch)  # relative to origin at (0,0) top of ascent
        adv = font.getlength(ch)
        if bbox is None or bbox[2] <= bbox[0]:
            w = h = 0
            img = None
            x0 = y0 = 0
        else:
            x0, y0, x1, y1 = bbox
            w, h = x1 - x0 + 2, y1 - y0 + 2
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0 + 1, -y0 + 1), ch, font=font, fill=255)
            x0 -= 1
            y0 -= 1
        glyphs.append(dict(cp=ord(ch), w=w, h=h, xo=x0, yo=y0, adv=round(adv), img=img))
    # shelf pack
    x = y = 0
    rowh = 0
    for g in sorted(glyphs, key=lambda g: -g["h"]):
        if g["w"] == 0:
            g["x"] = g["y"] = 0
            continue
        if x + g["w"] > ATLAS_W:
            x = 0
            y += rowh + 1
            rowh = 0
        g["x"], g["y"] = x, y
        x += g["w"] + 1
        rowh = max(rowh, g["h"])
    H = y + rowh + 1
    atlas = Image.new("L", (ATLAS_W, H), 0)
    for g in glyphs:
        if g["img"] is not None:
            atlas.paste(g["img"], (g["x"], g["y"]))
    return dict(ascent=ascent, descent=descent, line=ascent + descent, glyphs=glyphs, atlas=atlas, h=H)


def main(out):
    lines = ["/* generated by tools/mkfont.py - do not edit */", "#pragma once", "#include <stdint.h>", ""]
    lines.append("typedef struct { uint32_t cp; int16_t x, y, w, h, xo, yo, adv; } GlyphInfo;")
    lines.append("typedef struct { int ascent, line, atlas_w, atlas_h, nglyph; const GlyphInfo *g; const uint8_t *px; } FontInfo;")
    lines.append("enum { " + ", ".join(f[0] for f in FONTS) + ", F_COUNT };")
    infos = []
    for name, path, idx, size, chars in FONTS:
        b = bake(path, idx, size, chars)
        gs = sorted(b["glyphs"], key=lambda g: g["cp"])
        lines.append(f"static const GlyphInfo {name}_g[{len(gs)}] = {{")
        for g in gs:
            lines.append(f"  {{{g['cp']},{g['x']},{g['y']},{g['w']},{g['h']},{g['xo']},{g['yo']},{g['adv']}}},")
        lines.append("};")
        data = b["atlas"].tobytes()
        lines.append(f"static const uint8_t {name}_px[{len(data)}] = {{")
        for i in range(0, len(data), 40):
            lines.append(",".join(str(v) for v in data[i:i + 40]) + ",")
        lines.append("};")
        infos.append(f"  {{{b['ascent']},{b['line']},{ATLAS_W},{b['h']},{len(gs)},{name}_g,{name}_px}},")
        print(f"{name}: {len(gs)} glyphs, atlas {ATLAS_W}x{b['h']}", file=sys.stderr)
    lines.append("static const FontInfo FONT_INFO[F_COUNT] = {")
    lines += infos
    lines.append("};")
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
